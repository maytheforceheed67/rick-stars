/**
 * Room layouts for "Lawnmower Dog", as ASCII grids (legend in engine/dungeon/templates.ts).
 * Standard rooms are 15x9; the engine adds walls and doors around them. Terry's dream school
 * reuses the Pilot's school rooms.
 *
 * Episode markers:
 *   R  Rick          J  Jerry           N  Snuffles        C  Rick's ship     S  creaky board or searchlight
 *   B  a bed         V  a TV            c  the couch       b  batteries       A  a dog on patrol
 *   D  entry point   X  where the way out appears          T  Little Terry    G  the quiz teacher
 *   Y  the centaur and the velvet rope (Mrs. Pancakes' club)                  W  Snowball
 *   k  luxury props  Q  Goldenfold asleep
 */
import type { RoomTemplate } from '../../../engine/types';

const t = (id: string, rows: string[]): RoomTemplate => ({ id, rows });

/** Builds a row of `width` floor tiles with characters placed at given columns. */
function row(width: number, marks: Record<number, string> = {}, fill = '.'): string {
  const chars = Array.from({ length: width }, () => fill);
  for (const [col, ch] of Object.entries(marks)) chars[Number(col)] = ch;
  return chars.join('');
}

