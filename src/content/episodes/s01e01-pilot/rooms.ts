/**
 * Room layouts for the Pilot, as ASCII grids (legend in engine/dungeon/templates.ts).
 * Standard rooms are 15x9; the engine adds walls and doors around them.
 *
 * Pilot-specific markers:
 *   L  locker Frank can kick         G  Mr. Goldenfold's desk      T  Mega Tree
 *   F  Mega Fruit on the Big Tree    B  shoe battery pad           A  customs agent
 *   S  scanner gate                  Z  final checkpoint scanner    D  agent entry point
 *   X  where the exit appears        R  Rick                        C  flying car
 *   J/H/U  Jerry, Beth, Summer (epilogue)   b  moving box
 */
import type { RoomTemplate } from '../../../engine/types';

const t = (id: string, rows: string[]): RoomTemplate => ({ id, rows });

/** Builds a row of `width` floor tiles with characters placed at given columns. */
function row(width: number, marks: Record<number, string> = {}, fill = '.'): string {
  const chars = Array.from({ length: width }, () => fill);
  for (const [col, ch] of Object.entries(marks)) chars[Number(col)] = ch;
  return chars.join('');
}

